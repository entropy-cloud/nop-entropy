#!/usr/bin/env bash
# tools/install-cli.sh — Install nop-cli as a global command
#
# Copies the built uber-jar into ~/.nop/cli/ and registers a `nop-cli`
# command on PATH. Works in git bash (MSYS), macOS and Linux.
#
# Usage:
#   bash tools/install-cli.sh                # install / refresh
#   bash tools/install-cli.sh --build        # build the jar first if missing
#   bash tools/install-cli.sh --unregister   # remove the registration
#   bash tools/install-cli.sh --help
#
# Why copy instead of symlink the jar: this script is typically run from a
# git worktree, which may be deleted or replaced while the global command is
# still expected to work. The copy is self-contained under ~/.nop/cli.
# The PATH entry is a symlink to a small launcher inside ~/.nop/cli/bin, so
# re-running this script swaps the jar without touching the PATH entry.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

NOP_CLI_HOME="${NOP_CLI_HOME:-$HOME/.nop/cli}"
JAR_NAME="nop-cli.jar"
LAUNCHER_REL="bin/nop-cli"
COMMAND_NAME="nop-cli"

usage() {
    sed -n '3,20p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
}

log()  { printf '%s\n' "$*"; }
warn() { printf '%s\n' "$*" >&2; }
die()  { printf 'Error: %s\n' "$*" >&2; exit 1; }

# --- Java resolution -------------------------------------------------------
# nop-cli is compiled with `--release 22`, so it needs JDK 22 or newer.
resolve_java() {
    if [ -n "${JAVA_HOME:-}" ] && [ -x "$JAVA_HOME/bin/java" ]; then
        echo "$JAVA_HOME/bin/java"
        return 0
    fi
    if command -v java >/dev/null 2>&1; then
        command -v java
        return 0
    fi
    return 1
}

java_version_of() {
    "$1" -version 2>&1 | awk -F'"' '/version/ {print $2; exit}'
}

# --- Locate the built uber-jar --------------------------------------------
# nop-runner/nop-cli pins its own version (independent of the reactor), so the
# jar name is globbed rather than hardcoded. Excludes the Quarkus -runner jar
# and the auxiliary sources/tests/javadoc jars.
find_jar() {
    local target="$REPO_ROOT/nop-runner/nop-cli/target"
    [ -d "$target" ] || return 1
    local f
    for f in "$target"/nop-cli-*.jar; do
        [ -f "$f" ] || continue
        case "$f" in
            *-sources.jar|*-tests.jar|*-javadoc.jar|*-runner.jar|original-*) continue ;;
        esac
        echo "$f"
        return 0
    done
    return 1
}

build_jar() {
    log "==> Building nop-cli (this takes a few minutes: Quarkus uber-jar)..."
    log "    ./mvnw install -pl nop-runner/nop-cli-core -DskipTests"
    log "    ./mvnw install -pl nop-runner/nop-cli        -DskipTests"
    ( cd "$REPO_ROOT" \
      && ./mvnw install -pl nop-runner/nop-cli-core -DskipTests -q \
      && ./mvnw install -pl nop-runner/nop-cli -DskipTests -q )
}

# --- Write the launcher ----------------------------------------------------
write_launcher() {
    local launcher="$NOP_CLI_HOME/$LAUNCHER_REL"
    mkdir -p "$(dirname "$launcher")"
    cat > "$launcher" <<LAUNCHER
#!/usr/bin/env bash
# nop-cli launcher — generated by nop-entropy tools/install-cli.sh
# Re-run that script to upgrade; do not edit this file.
set -euo pipefail

NOP_CLI_JAR="\${NOP_CLI_JAR:-$NOP_CLI_HOME/$JAR_NAME}"

if [ ! -f "\$NOP_CLI_JAR" ]; then
    echo "nop-cli: jar not found at \$NOP_CLI_JAR" >&2
    echo "         reinstall with: bash <nop-entropy-repo>/tools/install-cli.sh" >&2
    exit 127
fi

if [ -n "\${JAVA_HOME:-}" ] && [ -x "\$JAVA_HOME/bin/java" ]; then
    JAVA="\$JAVA_HOME/bin/java"
elif command -v java >/dev/null 2>&1; then
    JAVA=java
else
    echo "nop-cli: no java found. Set JAVA_HOME to a JDK 22+ installation." >&2
    exit 127
fi

exec "\$JAVA" \${NOP_CLI_OPTS:-} -jar "\$NOP_CLI_JAR" "\$@"
LAUNCHER
    chmod +x "$launcher"
}

# --- Pick the directory to register into ----------------------------------
# Preference order: first candidate that is already on PATH wins, so we never
# have to modify the user's shell rc. Otherwise fall back to ~/.local/bin and
# tell the user which line to add.
pick_bin_dir() {
    local dir
    for dir in "$HOME/.local/bin" "$HOME/bin" /usr/local/bin; do
        case ":$PATH:" in
            *":$dir:"*) echo "$dir"; return 0 ;;
        esac
    done
    echo "$HOME/.local/bin"
}

path_has_dir() {
    case ":$PATH:" in
        *":$1:"*) return 0 ;;
        *) return 1 ;;
    esac
}

rc_hint() {
    case "${SHELL:-}" in
        *zsh)  printf 'echo %s\047%s\047 >> ~/.zshrc' 'export PATH="' "$1" ;;
        *bash) printf 'echo %s\047%s\047 >> ~/.bashrc' 'export PATH="' "$1" ;;
        *)    printf 'echo %s\047%s\047 >> ~/.profile' 'export PATH="' "$1" ;;
    esac
}

# --- Subcommands -----------------------------------------------------------
do_install() {
    local do_build="$1"

    if ! JAVA_BIN="$(resolve_java)"; then
        die "no java found on PATH and JAVA_HOME is unset. Install JDK 22 or newer."
    fi
    local jver; jver="$(java_version_of "$JAVA_BIN")"
    log "==> java: $JAVA_BIN (version $jver)"

    if ! JAR="$(find_jar)"; then
        if [ "$do_build" = "build" ]; then
            build_jar
        fi
        if ! JAR="$(find_jar)"; then
            warn "nop-cli uber-jar not found under $REPO_ROOT/nop-runner/nop-cli/target"
            warn ""
            warn "Build it first:"
            warn "  ./mvnw install -pl nop-runner/nop-cli-core -DskipTests"
            warn "  ./mvnw install -pl nop-runner/nop-cli        -DskipTests"
            warn ""
            warn "or re-run this script with --build"
            exit 1
        fi
    fi
    log "==> jar:   $JAR ($(du -h "$JAR" | cut -f1))"

    mkdir -p "$NOP_CLI_HOME"
    # Copy atomically so an interrupted run cannot leave a truncated jar.
    cp "$JAR" "$NOP_CLI_HOME/$JAR_NAME.new"
    mv "$NOP_CLI_HOME/$JAR_NAME.new" "$NOP_CLI_HOME/$JAR_NAME"
    log "==> copied to $NOP_CLI_HOME/$JAR_NAME"

    write_launcher

    BIN_DIR="$(pick_bin_dir)"
    mkdir -p "$BIN_DIR" 2>/dev/null || die "cannot create $BIN_DIR"
    LINK="$BIN_DIR/$COMMAND_NAME"

    # A stale symlink from a previous install (e.g. a deleted worktree) must
    # go first: `ln -s` would otherwise fail or nest the link.
    if [ -L "$LINK" ] || [ -e "$LINK" ]; then
        rm -f "$LINK"
    fi
    if ln -s "$NOP_CLI_HOME/$LAUNCHER_REL" "$LINK" 2>/dev/null; then
        log "==> registered $COMMAND_NAME -> $NOP_CLI_HOME/$LAUNCHER_REL (in $BIN_DIR)"
    else
        # Filesystems without symlink support (some Windows setups): install a
        # self-contained forwarding script instead.
        cat > "$LINK" <<FORWARD
#!/usr/bin/env bash
exec "$NOP_CLI_HOME/$LAUNCHER_REL" "\$@"
FORWARD
        chmod +x "$LINK"
        log "==> registered $COMMAND_NAME -> $NOP_CLI_HOME/$LAUNCHER_REL (wrapper, symlink unsupported)"
    fi

    log ""
    if path_has_dir "$BIN_DIR"; then
        log "==> $BIN_DIR is already on PATH — '$COMMAND_NAME' is ready."
    else
        log "==> $BIN_DIR is NOT on PATH. Add it:"
        log ""
        log "    $(rc_hint "$BIN_DIR")"
        log ""
        log "    then restart your terminal (or 'source' the rc file)."
    fi
}

do_unregister() {
    local removed=0 failed=0 dir
    # Only the PATH entries are removed. $NOP_CLI_HOME/bin/$COMMAND_NAME is the
    # installed launcher itself, not a registration — deleting it would break a
    # later re-install's target, so it stays.
    for dir in "$HOME/.local/bin" "$HOME/bin" /usr/local/bin; do
        local link="$dir/$COMMAND_NAME"
        [ -L "$link" ] || [ -f "$link" ] || continue
        if rm -f "$link" 2>/dev/null; then
            log "==> removed $link"
            removed=1
        else
            warn "==> could not remove $link (needs elevated permissions)"
            failed=1
        fi
    done
    if [ "$removed" = "0" ] && [ "$failed" = "0" ]; then
        log "==> no '$COMMAND_NAME' registration found; nothing to remove"
    fi
    log ""
    log "The installed jar at $NOP_CLI_HOME/$JAR_NAME was left in place."
    log "Delete $NOP_CLI_HOME to remove it as well."
}

# --- Entry point -----------------------------------------------------------
case "${1:-install}" in
    install)      do_install nostub ;;
    --build|build) do_install build ;;
    --unregister|uninstall) do_unregister ;;
    -h|--help|help) usage ;;
    *) die "unknown argument '$1' (try --help)" ;;
esac