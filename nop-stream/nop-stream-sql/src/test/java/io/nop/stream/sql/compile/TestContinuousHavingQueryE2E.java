/**
 * WI17 (plan 2342) wiring evidence: the continuous HAVING filter node sits between
 * the reduce row map and the projection in the compiled model, survives the
 * DslModelParser → StreamModelDslBuilder round trip, and drops running rows at
 * execution time (the sum&lt;=0 tail row is filtered out). One execute per class —
 * the fixed source bean is one-shot per container (cancel() is terminal).
 */
public class TestContinuousHavingQueryE2E {

    private static IBeanContainerImplementor container;

    @BeforeAll
    public static void init() {
        CoreInitialization.initializeTo(CoreConstants.INITIALIZER_PRIORITY_IOC - 1);
        BeanContainerBuilder builder = new BeanContainerBuilder(null);
        builder.addResource(new ClassPathResource(
                "classpath:_vfs/nop/stream/sql/test/sql-compile.beans.xml"));
        builder.addResource(new ClassPathResource(
                "classpath:_vfs/nop/stream/sql/beans/app-aggregator.beans.xml"));
        container = builder.build("sql-continuous-having-e2e");
        container.start();
        BeanContainer.registerInstance(container);
    }

    @AfterAll
    public static void destroy() {
        if (container != null)
            container.stop();
        CoreInitialization.destroy();
        BeanContainer.registerInstance(null);
    }

    @Test
    public void havingFiltersRunningRowsEndToEnd() throws Exception {
        String xml = StreamSqlCompiler.compile(null,
                "SELECT item, sum(amount) AS s FROM orders GROUP BY item HAVING sum(amount) > 0",
                TestStreamSqlCompiler.ORDERS_SCHEMA, "testSink");
        StreamModel model = (StreamModel) new DslModelParser().parseFromNode(XNode.parse(xml));
        StreamExecutionEnvironment env = StreamModelDslBuilder.of(model).build();
        env.execute("continuous-having-e2e");

        SqlTestSink sink = (SqlTestSink) BeanContainer.instance().getBean("testSink");
        List<String> rows = sink.getCollected().stream()
                .map(o -> {
                    Map<?, ?> m = (Map<?, ?>) o;
                    return m.get("item") + "=" + m.get("s");
                })
                .collect(Collectors.toList());
        // running sums a:1, b:2, a:1(null skipped), a:4, b:6, a:-1, c:1 — the sum<=0
        // tail (a=-1) is dropped by the HAVING filter after the aggregate
        assertEquals(Arrays.asList("a=1", "b=2", "a=1", "a=4", "b=6", "c=1"),
                rows, () -> "having rows: " + rows);
    }
}
