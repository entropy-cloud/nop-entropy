class Branchy {
    int pick(int a) {
        int total = 0;
        if (a == 1) { total += 1; }
        if (a == 2) { total += 2; }
        if (a == 3) { total += 3; }
        if (a == 4) { total += 4; }
        if (a == 5) { total += 5; }
        if (a == 6) { total += 6; }
        if (a == 7) { total += 7; }
        if (a == 8) { total += 8; }
        return total;
    }
}
