package io.nop.treesitter.scanner;

import static io.nop.treesitter.scanner.BashCharClass.isAlpha;
import static io.nop.treesitter.scanner.BashCharClass.isSpace;
import static io.nop.treesitter.scanner.BashExpansionScanner.EXPANSION_WORD;
import static io.nop.treesitter.scanner.BashExtglobScanner.EXTGLOB_PATTERN;
import static io.nop.treesitter.scanner.BashRegexScanner.REGEX_NO_SLASH;
import static io.nop.treesitter.scanner.BashRegexScanner.REGEX_NO_SPACE;
import static io.nop.treesitter.scanner.BashScanFlow.CONTINUE;
import static io.nop.treesitter.scanner.BashScanFlow.MATCHED;
import static io.nop.treesitter.scanner.BashScanFlow.NO_MATCH;

/**
 * Faithful Java translation of tree-sitter-bash's {@code scanner.c}
 * (upstream tag {@code v0.25.1}, commit
 * {@code a06c2e4415e9bc0346c6b86d401879ffb44058f7}, generated by tree-sitter
 * v0.25.10), covering all 29 external tokens.
 *
 * <p>The upstream {@code scan()} is a single function built from a fixed
 * sequence of guarded regions plus four {@code goto} labels. That control flow is
 * reproduced literally rather than refactored, because the ordering is
 * load-bearing: several regions share the same lookahead character and the
 * grammar's valid-symbol list decides which one wins. Two devices keep it
 * faithful in Java:</p>
 *
 * <ul>
 *   <li>{@link BashScanFlow} distinguishes "region rejected" ({@code return
 *       false}, aborts the scan) from "region guard did not fire" (fall through
 *       to the next region). A plain {@code boolean} cannot express both.</li>
 *   <li>Each {@code goto} target becomes a method that runs its target label
 *       <em>and every label after it</em>, matching C's fall-through between
 *       adjacent labels.</li>
 * </ul>
 *
 * <p>The regions themselves live in sibling classes to keep this file inside
 * the repository's 700-line oversized-file threshold:
 * {@link BashHeredocScanner} (heredoc body/end/start),
 * {@link BashRegexScanner} ({@code regex:}),
 * {@link BashExtglobScanner} ({@code extglob_pattern:}),
 * {@link BashExpansionScanner} ({@code expansion_word:} and
 * {@code brace_start:}).</p>
 *
 * <p>Character classes are the C-locale ASCII predicates (see
 * {@link BashCharClass}); the deliberately redundant-looking upstream tests such
 * as {@code iswspace(c) && c != '\n'} are preserved as written.</p>
 */
public final class BashScanner implements ExternalScanner {

    // external token ordinals (scanner.c enum TokenType order == the
    // ts_external_scanner_symbol_identifiers order of the vendored parser.c)
    private static final int EMPTY_VALUE = 6;
    private static final int CONCAT = 7;
    private static final int TEST_OPERATOR = 9;
    private static final int BARE_DOLLAR = 15;
    private static final int IMMEDIATE_DOUBLE_HASH = 17;
    private static final int EXTERNAL_EXPANSION_SYM_HASH = 18;
    private static final int EXTERNAL_EXPANSION_SYM_BANG = 19;
    private static final int EXTERNAL_EXPANSION_SYM_EQUAL = 20;
    private static final int CLOSING_BRACE = 21;
    private static final int CLOSING_BRACKET = 22;
    private static final int NEWLINE = 25;

    private final BashScannerState state = new BashScannerState();

    public BashScanner() {
        deserialize(new byte[0]);
    }

    /** {@code in_error_recovery}: the ERROR_RECOVERY external token is valid. */
    static boolean inErrorRecovery(boolean[] validSymbols) {
        return validSymbols[28];
    }

    @Override
    public boolean scan(ExternalScanContext ctx, boolean[] valid) {
        int flow = regionConcat(ctx, valid);
        if (BashScanFlow.isTerminal(flow)) {
            return BashScanFlow.result(flow);
        }
        flow = regionImmediateDoubleHash(ctx, valid);
        if (BashScanFlow.isTerminal(flow)) {
            return BashScanFlow.result(flow);
        }
        flow = regionExpansionSymHash(ctx, valid);
        if (BashScanFlow.isTerminal(flow)) {
            return BashScanFlow.result(flow);
        }
        flow = regionEmptyValue(ctx, valid);
        if (BashScanFlow.isTerminal(flow)) {
            return BashScanFlow.result(flow);
        }
        flow = BashHeredocScanner.regionBodyBeginning(state, ctx, valid);
        if (BashScanFlow.isTerminal(flow)) {
            return BashScanFlow.result(flow);
        }
        flow = BashHeredocScanner.regionHeredocEnd(state, ctx, valid);
        if (BashScanFlow.isTerminal(flow)) {
            return BashScanFlow.result(flow);
        }
        flow = BashHeredocScanner.regionHeredocContent(state, ctx, valid);
        if (BashScanFlow.isTerminal(flow)) {
            return BashScanFlow.result(flow);
        }
        flow = BashHeredocScanner.regionHeredocStart(state, ctx, valid);
        if (BashScanFlow.isTerminal(flow)) {
            return BashScanFlow.result(flow);
        }
        flow = regionTestOperator(ctx, valid);
        if (BashScanFlow.isTerminal(flow)) {
            return resolveLabel(ctx, valid, flow);
        }
        flow = BashVariableNameScanner.region(state, ctx, valid);
        if (BashScanFlow.isTerminal(flow)) {
            return resolveLabel(ctx, valid, flow);
        }
        flow = regionBareDollar(ctx, valid);
        if (BashScanFlow.isTerminal(flow)) {
            return BashScanFlow.result(flow);
        }
        return resolveLabel(ctx, valid, BashScanFlow.JUMP_REGEX);
    }

    // ---- regions in scan() file order -------------------------------------

    private static int regionConcat(ExternalScanContext ctx, boolean[] valid) {
        if (!valid[CONCAT] || inErrorRecovery(valid)) {
            return CONTINUE;
        }
        int c = ctx.lookahead();
        boolean delimiter = c == 0 || isSpace(c) || c == '>' || c == '<' || c == ')'
                || c == '(' || c == ';' || c == '&' || c == '|'
                || (c == '}' && valid[CLOSING_BRACE])
                || (c == ']' && valid[CLOSING_BRACKET]);
        if (!delimiter) {
            ctx.setResultSymbol(CONCAT);
            // So for a`b`, we want to return a concat. We check if the
            // 2nd backtick has whitespace after it, and if it does we
            // return concat.
            if (c == '`') {
                ctx.markEnd();
                ctx.advance(false);
                while (ctx.lookahead() != '`' && !ctx.eof()) {
                    ctx.advance(false);
                }
                if (ctx.eof()) {
                    return NO_MATCH;
                }
                if (ctx.lookahead() == '`') {
                    ctx.advance(false);
                }
                return isSpace(ctx.lookahead()) || ctx.eof() ? MATCHED : NO_MATCH;
            }
            // strings w/ expansions that contain escaped quotes or
            // backslashes need this to return a concat
            if (c == '\\') {
                ctx.markEnd();
                ctx.advance(false);
                int next = ctx.lookahead();
                if (next == '"' || next == '\'' || next == '\\') {
                    return MATCHED;
                }
                if (ctx.eof()) {
                    return NO_MATCH;
                }
            } else {
                return MATCHED;
            }
        }
        if (isSpace(ctx.lookahead()) && valid[CLOSING_BRACE] && !valid[EXPANSION_WORD]) {
            ctx.setResultSymbol(CONCAT);
            return MATCHED;
        }
        return CONTINUE;
    }

    private static int regionImmediateDoubleHash(ExternalScanContext ctx, boolean[] valid) {
        if (valid[IMMEDIATE_DOUBLE_HASH] && !inErrorRecovery(valid) && ctx.lookahead() == '#') {
            // advance two # and ensure not } after
            ctx.markEnd();
            ctx.advance(false);
            if (ctx.lookahead() == '#') {
                ctx.advance(false);
                if (ctx.lookahead() != '}') {
                    ctx.setResultSymbol(IMMEDIATE_DOUBLE_HASH);
                    ctx.markEnd();
                    return MATCHED;
                }
            }
        }
        return CONTINUE;
    }

    private static int regionExpansionSymHash(ExternalScanContext ctx, boolean[] valid) {
        if (valid[EXTERNAL_EXPANSION_SYM_HASH] && !inErrorRecovery(valid)) {
            int c = ctx.lookahead();
            if (c == '#' || c == '=' || c == '!') {
                ctx.setResultSymbol(c == '#' ? EXTERNAL_EXPANSION_SYM_HASH
                        : c == '!' ? EXTERNAL_EXPANSION_SYM_BANG : EXTERNAL_EXPANSION_SYM_EQUAL);
                ctx.advance(false);
                ctx.markEnd();
                while (ctx.lookahead() == '#' || ctx.lookahead() == '=' || ctx.lookahead() == '!') {
                    ctx.advance(false);
                }
                while (isSpace(ctx.lookahead())) {
                    ctx.advance(true);
                }
                return ctx.lookahead() == '}' ? MATCHED : NO_MATCH;
            }
        }
        return CONTINUE;
    }

    private static int regionEmptyValue(ExternalScanContext ctx, boolean[] valid) {
        if (valid[EMPTY_VALUE]) {
            int c = ctx.lookahead();
            if (isSpace(c) || ctx.eof() || c == ';' || c == '&') {
                ctx.setResultSymbol(EMPTY_VALUE);
                return MATCHED;
            }
        }
        return CONTINUE;
    }

    private static int regionTestOperator(ExternalScanContext ctx, boolean[] valid) {
        if (!valid[TEST_OPERATOR] || valid[EXPANSION_WORD]) {
            return CONTINUE;
        }
        while (isSpace(ctx.lookahead()) && ctx.lookahead() != '\n') {
            ctx.advance(true);
        }

        if (ctx.lookahead() == '\\') {
            if (valid[EXTGLOB_PATTERN]) {
                return BashScanFlow.JUMP_EXTGLOB;
            }
            if (valid[REGEX_NO_SPACE]) {
                return BashScanFlow.JUMP_REGEX;
            }
            ctx.advance(true);

            if (ctx.eof()) {
                return NO_MATCH;
            }

            if (ctx.lookahead() == '\r') {
                ctx.advance(true);
                if (ctx.lookahead() == '\n') {
                    ctx.advance(true);
                }
            } else if (ctx.lookahead() == '\n') {
                ctx.advance(true);
            } else {
                return NO_MATCH;
            }

            while (isSpace(ctx.lookahead())) {
                ctx.advance(true);
            }
        }

        if (ctx.lookahead() == '\n' && !valid[NEWLINE]) {
            ctx.advance(true);
            while (isSpace(ctx.lookahead())) {
                ctx.advance(true);
            }
        }

        if (ctx.lookahead() == '-') {
            ctx.advance(false);

            boolean advancedOnce = false;
            while (isAlpha(ctx.lookahead())) {
                advancedOnce = true;
                ctx.advance(false);
            }

            if (isSpace(ctx.lookahead()) && advancedOnce) {
                ctx.markEnd();
                ctx.advance(false);
                if (ctx.lookahead() == '}' && valid[CLOSING_BRACE]) {
                    // Upstream nests `if (valid_symbols[EXPANSION_WORD])` here, but this
                    // region's guard is TEST_OPERATOR && !EXPANSION_WORD, so that branch
                    // is unreachable and only its `return false` can run.
                    return NO_MATCH;
                }
                ctx.setResultSymbol(TEST_OPERATOR);
                return MATCHED;
            }
            if (isSpace(ctx.lookahead()) && valid[EXTGLOB_PATTERN]) {
                ctx.setResultSymbol(EXTGLOB_PATTERN);
                return MATCHED;
            }
        }

        if (valid[BARE_DOLLAR] && !inErrorRecovery(valid) && scanBareDollar(ctx)) {
            return MATCHED;
        }
        return CONTINUE;
    }

    private static int regionBareDollar(ExternalScanContext ctx, boolean[] valid) {
        if (valid[BARE_DOLLAR] && !inErrorRecovery(valid) && scanBareDollar(ctx)) {
            return MATCHED;
        }
        return CONTINUE;
    }

    /** {@code scan_bare_dollar}; has lexer side effects even when it returns false. */
    private static boolean scanBareDollar(ExternalScanContext ctx) {
        while (isSpace(ctx.lookahead()) && ctx.lookahead() != '\n' && !ctx.eof()) {
            ctx.advance(true);
        }

        if (ctx.lookahead() == '$') {
            ctx.advance(false);
            ctx.setResultSymbol(BARE_DOLLAR);
            ctx.markEnd();
            return isSpace(ctx.lookahead()) || ctx.eof() || ctx.lookahead() == '"';
        }

        return false;
    }

    // ---- goto targets ------------------------------------------------------

    /**
     * Runs the label a {@code goto} names, together with every label after it in
     * {@code scanner.c} file order (C falls through between adjacent labels).
     */
    private boolean resolveLabel(ExternalScanContext ctx, boolean[] valid, int label) {
        switch (label) {
            case BashScanFlow.JUMP_REGEX: {
                int flow = BashRegexScanner.region(ctx, valid);
                return BashScanFlow.isTerminal(flow) ? BashScanFlow.result(flow)
                        : resolveLabel(ctx, valid, BashScanFlow.JUMP_EXTGLOB);
            }
            case BashScanFlow.JUMP_EXTGLOB: {
                int flow = BashExtglobScanner.region(state, ctx, valid);
                return BashScanFlow.isTerminal(flow) ? BashScanFlow.result(flow)
                        : resolveLabel(ctx, valid, BashScanFlow.JUMP_EXPANSION_WORD);
            }
            case BashScanFlow.JUMP_EXPANSION_WORD: {
                int flow = BashExpansionScanner.regionExpansionWord(ctx, valid);
                return BashScanFlow.isTerminal(flow) ? BashScanFlow.result(flow)
                        : resolveLabel(ctx, valid, BashScanFlow.JUMP_BRACE_START);
            }
            case BashScanFlow.JUMP_BRACE_START:
                return BashScanFlow.result(BashExpansionScanner.regionBraceStart(ctx, valid));
            default:
                return BashScanFlow.result(label);
        }
    }

    // ---- cross-call state --------------------------------------------------

    @Override
    public byte[] serialize() {
        return state.serialize();
    }

    @Override
    public void deserialize(byte[] state) {
        this.state.deserialize(state);
    }
}
